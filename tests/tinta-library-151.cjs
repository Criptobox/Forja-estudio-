const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const catalog = JSON.parse(fs.readFileSync(path.join(root, 'design-library/catalog.json'), 'utf8'));
const records = catalog.records;
const ids = records.map(r => r.id);
const slugs = records.map(r => r.slug);
const icons = records.filter(r => r.id.startsWith('icon-'));
assert.equal(records.length, 158, 'catalog keeps the 138 existing records and adds 20 icons');
assert.equal(new Set(ids).size, records.length, 'all catalog IDs remain unique');
assert.equal(new Set(slugs).size, records.length, 'all catalog slugs are unique');
assert.equal(icons.length, 20, '20 new local SVG icon records');
assert.ok(icons.every(r => r.module === 'icons' && r.type === 'resource'), 'icon records are resources in the icon module');
assert.ok(records.some(r => r.styles.includes('solid')), 'solid treatment is detected from CSS');
assert.ok(records.every(r => ['component','resource','template'].includes(r.type)), 'all records have a supported type');
const html = fs.readFileSync(path.join(root, 'web/crear.html'), 'utf8');
const js = fs.readFileSync(path.join(root, 'web/js/crear.js'), 'utf8');
const catalogJs = fs.readFileSync(path.join(root, 'web/js/tinta-catalog.js'), 'utf8');
assert.match(html, /id="catalogType"/, 'type filter is present');
assert.match(html, /value="solid"/, 'solid filter is present');
assert.match(js, /catalogType.*addEventListener/, 'type filter is wired');
assert.match(js, /metadata\.type===state\.type/, 'type filter affects gallery results');
assert.match(catalogJs, /slugCounts/, 'duplicate slugs are made deterministic and unique');
console.log('Estilos 15.1: 11 comprobaciones de catálogo, iconos, slugs y filtros correctas.');
